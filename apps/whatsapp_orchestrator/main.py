"""WhatsApp bridge orchestrator — one isolated container per paired user.

Ported from AI_Marketplace's services/whatsapp-orchestrator. The only service
in this stack with /var/run/docker.sock mounted: its entire job is starting,
polling and removing one whatsapp-bridge container per (server, user) bridge
instance. The backend and worker run arbitrary vendor-registered MCP servers
and never get docker access themselves, so a compromise there can't turn into
"launch arbitrary containers on the host".

Narrow by construction: every endpoint takes an instance id (validated as a
bare UUID before it goes anywhere near a container/volume name) and does one
fixed operation on the ONE configured bridge image. Nothing here accepts an
image name, a command, a mount or any other docker primitive from the caller.

Each bridge container gets:
  - its own named volume (``eai-wa-store-<id>``) for the WhatsApp session and
    message history — never visible to the backend or to other bridges;
  - a per-instance token (generated by the backend) its REST API requires on
    every request, since the backend/worker share the bridge network;
  - a memory/CPU/pids cap and no Linux capabilities.
"""
from __future__ import annotations

import hmac
import json
import os
import re
import urllib.error
import urllib.request

import docker
import docker.errors
from fastapi import Body, FastAPI, Header, HTTPException

app = FastAPI(title="enterpriseai-whatsapp-orchestrator")
client = docker.from_env()

API_KEY = os.environ["ORCHESTRATOR_API_KEY"]
BRIDGE_IMAGE = os.environ.get("WHATSAPP_BRIDGE_IMAGE", "enterpriseai-whatsapp-bridge:latest")
NETWORK = os.environ.get("WHATSAPP_NETWORK", "enterpriseai_whatsapp")
# Hard ceiling on bridge containers (0 = unlimited) — each holds a live
# WhatsApp Web session and costs up to 256MB + 0.5 vCPU.
MAX_CONTAINERS = int(os.environ.get("WHATSAPP_MAX_CONTAINERS", "0") or 0)

_ID_RE = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")
_TOKEN_RE = re.compile(r"^[A-Za-z0-9_-]{32,128}$")
_PHONE_RE = re.compile(r"^[1-9][0-9]{6,14}$")  # E.164 digits, no "+"
_LABEL = "enterpriseai.whatsapp-bridge"


def _check_key(x_api_key: str | None) -> None:
    if not x_api_key or not hmac.compare_digest(x_api_key, API_KEY):
        raise HTTPException(status_code=401, detail="invalid or missing X-API-Key")


def _validate_id(instance_id: str) -> None:
    if not _ID_RE.match(instance_id):
        raise HTTPException(status_code=400, detail="instance_id must be a UUID")


def _container_name(instance_id: str) -> str:
    return f"eai-wa-bridge-{instance_id}"


def _volume_name(instance_id: str) -> str:
    return f"eai-wa-store-{instance_id}"


def _container_token(container) -> str:
    for item in container.attrs.get("Config", {}).get("Env") or []:
        key, _, value = item.partition("=")
        if key == "WHATSAPP_BRIDGE_TOKEN":
            return value
    return ""


@app.post("/instances/{instance_id}/start")
def start_instance(
    instance_id: str,
    token: str = Body(..., embed=True),
    x_api_key: str | None = Header(None),
):
    _check_key(x_api_key)
    _validate_id(instance_id)
    if not _TOKEN_RE.match(token):
        raise HTTPException(status_code=400, detail="token must be 32-128 url-safe characters")
    name = _container_name(instance_id)

    try:
        existing = client.containers.get(name)
    except docker.errors.NotFound:
        existing = None
    if existing is not None:
        if hmac.compare_digest(_container_token(existing), token):
            if existing.status != "running":
                existing.start()
            elif _bridge_status(name, existing).get("status") != "connected":
                # Connect always means a fresh QR: a bridge still waiting has an
                # expired one (WhatsApp's last ~20-60s), or is stuck after a
                # timeout or a logout. A linked session (kept in the volume) is
                # left alone.
                existing.restart(timeout=5)
            return {"status": "starting"}
        # Token rotated (e.g. after "forget"): a container's env is fixed at
        # creation, so recreate it — the session volume is kept.
        existing.remove(force=True)

    if MAX_CONTAINERS:
        count = len(client.containers.list(all=True, filters={"label": _LABEL}))
        if count >= MAX_CONTAINERS:
            raise HTTPException(status_code=429, detail=f"bridge container limit reached ({MAX_CONTAINERS})")

    volume = _volume_name(instance_id)
    try:
        client.volumes.get(volume)
    except docker.errors.NotFound:
        client.volumes.create(volume, labels={_LABEL: instance_id})

    client.containers.run(
        BRIDGE_IMAGE,
        name=name,
        detach=True,
        network=NETWORK,
        environment={
            "WHATSAPP_BRIDGE_HOST": "0.0.0.0",
            "WHATSAPP_BRIDGE_PORT": "8080",
            "WHATSAPP_BRIDGE_TOKEN": token,
        },
        volumes={volume: {"bind": "/app/store", "mode": "rw"}},
        labels={_LABEL: instance_id},
        restart_policy={"Name": "unless-stopped"},
        mem_limit="256m",
        nano_cpus=500_000_000,  # 0.5 vCPU
        pids_limit=256,
        cap_drop=["ALL"],
        security_opt=["no-new-privileges"],
    )
    return {"status": "starting"}


@app.get("/instances/{instance_id}/status")
def instance_status(instance_id: str, x_api_key: str | None = Header(None)):
    _check_key(x_api_key)
    _validate_id(instance_id)
    name = _container_name(instance_id)

    try:
        c = client.containers.get(name)
    except docker.errors.NotFound:
        return {"status": "not_started", "qr": ""}
    if c.status != "running":
        return {"status": c.status, "qr": ""}
    return _bridge_status(name, c)


def _bridge_status(name: str, c) -> dict:
    """Proxy the bridge's own /api/status over the bridge network. A bridge
    still booting isn't answering HTTP yet — that's "starting", not an error."""
    req = urllib.request.Request(
        f"http://{name}:8080/api/status",
        headers={"X-Bridge-Token": _container_token(c)},
    )
    try:
        with urllib.request.urlopen(req, timeout=5) as r:
            return json.load(r)
    except (urllib.error.URLError, TimeoutError, ConnectionError):
        return {"status": "starting", "qr": ""}


@app.post("/instances/{instance_id}/pair-phone")
def pair_phone(
    instance_id: str,
    phone: str = Body(..., embed=True),
    x_api_key: str | None = Header(None),
):
    """Ask the bridge for a phone-number pairing code (the alternative to
    scanning its QR) — proxied to its own /api/pair-phone."""
    _check_key(x_api_key)
    _validate_id(instance_id)
    if not _PHONE_RE.match(phone):
        raise HTTPException(status_code=400, detail="phone must be digits with country code, e.g. 919876543210")
    name = _container_name(instance_id)

    try:
        c = client.containers.get(name)
    except docker.errors.NotFound:
        raise HTTPException(status_code=409, detail="bridge is not running")
    if c.status != "running":
        raise HTTPException(status_code=409, detail="bridge is not running")

    req = urllib.request.Request(
        f"http://{name}:8080/api/pair-phone",
        data=json.dumps({"phone": phone}).encode(),
        headers={"X-Bridge-Token": _container_token(c), "Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=25) as r:
            return json.load(r)
    except urllib.error.HTTPError as exc:
        # The bridge's own refusal (bad number, not waiting to be paired) —
        # pass its status and plain-text reason through.
        raise HTTPException(status_code=exc.code, detail=exc.read().decode(errors="replace").strip()[:200])
    except (urllib.error.URLError, TimeoutError, ConnectionError):
        raise HTTPException(status_code=502, detail="bridge unreachable")


@app.delete("/instances/{instance_id}")
def stop_instance(instance_id: str, purge: bool = False, x_api_key: str | None = Header(None)):
    """Remove the bridge container. ``purge=true`` also deletes its session
    volume (WhatsApp pairing + message history) — "forget this device"."""
    _check_key(x_api_key)
    _validate_id(instance_id)

    try:
        client.containers.get(_container_name(instance_id)).remove(force=True)
    except docker.errors.NotFound:
        pass

    purged = False
    if purge:
        try:
            client.volumes.get(_volume_name(instance_id)).remove(force=True)
            purged = True
        except docker.errors.NotFound:
            purged = True
        except docker.errors.APIError:
            purged = False
    return {"status": "removed", "purged": purged}


@app.get("/health")
def health():
    return {"status": "ok"}
